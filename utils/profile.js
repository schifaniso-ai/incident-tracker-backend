const fs = require('fs/promises');
const path = require('path');

const EMAIL_PATTERN = /^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/;
const MAX_NAME_LENGTH = 100;
const MAX_EMAIL_LENGTH = 254;
const MAX_IMAGE_BYTES = 5 * 1024 * 1024;

const ALLOWED_IMAGE_TYPES = {
  'image/jpeg': 'jpg',
  'image/png': 'png',
  'image/webp': 'webp',
};

/**
 * Trim text, collapse repeated whitespace and remove characters that should
 * never be stored in a display name. Queries are parameterised separately to
 * prevent SQL injection; this helper mainly protects against stored markup.
 */
function normalizeName(value) {
  if (typeof value !== 'string') return '';

  return value
    .replace(/[\u0000-\u001f\u007f]/g, ' ')
    .replace(/[<>]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

function normalizeEmail(value) {
  if (typeof value !== 'string') return '';

  return value
    .replace(/[\u0000-\u001f\u007f]/g, '')
    .replace(/\s+/g, '')
    .trim()
    .toLowerCase();
}

/**
 * Validate the name and email fields used by POST /api/profile and
 * PUT /api/profile. Both fields are required and are validated again on the
 * server so a client cannot bypass the form by calling the API directly.
 */
function validateProfileFields(body = {}) {
  const name = normalizeName(body.name);
  const email = normalizeEmail(body.email);
  const errors = {};

  if (!name) {
    errors.name = 'Name is required.';
  } else if (name.length > MAX_NAME_LENGTH) {
    errors.name = `Name must be ${MAX_NAME_LENGTH} characters or fewer.`;
  }

  if (!email) {
    errors.email = 'Email is required.';
  } else if (email.length > MAX_EMAIL_LENGTH) {
    errors.email = `Email must be ${MAX_EMAIL_LENGTH} characters or fewer.`;
  } else if (!EMAIL_PATTERN.test(email)) {
    errors.email = 'Enter a valid email address.';
  }

  return {
    name,
    email,
    errors,
    isValid: Object.keys(errors).length === 0,
  };
}

/**
 * Detect an image by its first bytes instead of trusting the filename or the
 * browser-supplied MIME type. Returns the canonical extension or null.
 */
function detectImageType(buffer) {
  if (!Buffer.isBuffer(buffer) || buffer.length < 12) return null;

  const isJpeg =
    buffer[0] === 0xff && buffer[1] === 0xd8 && buffer[2] === 0xff;

  const isPng =
    buffer[0] === 0x89 &&
    buffer[1] === 0x50 &&
    buffer[2] === 0x4e &&
    buffer[3] === 0x47 &&
    buffer[4] === 0x0d &&
    buffer[5] === 0x0a &&
    buffer[6] === 0x1a &&
    buffer[7] === 0x0a;

  const isWebp =
    buffer.toString('ascii', 0, 4) === 'RIFF' &&
    buffer.toString('ascii', 8, 12) === 'WEBP';

  if (isJpeg) return 'jpg';
  if (isPng) return 'png';
  if (isWebp) return 'webp';

  return null;
}

/**
 * Validate the uploaded image against the declared MIME type and its magic
 * bytes. The returned extension is generated by the server, not the client.
 */
function validateProfileImage(file) {
  if (!file) {
    return { error: 'Choose a profile picture to upload.' };
  }

  if (!ALLOWED_IMAGE_TYPES[file.mimetype]) {
    return { error: 'Profile pictures must be JPG, PNG or WEBP images.' };
  }

  if (file.size > MAX_IMAGE_BYTES) {
    return { error: 'Profile pictures must be 5 MB or smaller.' };
  }

  const detectedType = detectImageType(file.buffer);

  if (!detectedType) {
    return {
      error: 'That file does not appear to be a valid JPG, PNG or WEBP image.',
    };
  }

  if (ALLOWED_IMAGE_TYPES[file.mimetype] !== detectedType) {
    return {
      error: 'The image contents do not match the selected file type.',
    };
  }

  return { extension: detectedType };
}

/**
 * Remove a previously uploaded profile picture. Only files inside the managed
 * uploads directory are touched, and the basename check blocks path traversal.
 */
async function deleteStoredImage(imageUrl, uploadsDirectory) {
  if (!imageUrl || typeof imageUrl !== 'string') return;

  const basename = path.basename(imageUrl);

  if (!/^[a-zA-Z0-9._-]+$/.test(basename)) return;

  const filePath = path.resolve(uploadsDirectory, basename);

  if (!filePath.startsWith(`${path.resolve(uploadsDirectory)}${path.sep}`)) {
    return;
  }

  try {
    await fs.unlink(filePath);
  } catch (error) {
    if (error.code !== 'ENOENT') {
      console.error('Could not delete profile image:', error.message);
    }
  }
}

/** Convert a database row into the public profile shape. */
function mapProfile(row) {
  if (!row) return null;

  return {
    id: row.id,
    name: row.name,
    email: row.email,
    profileImageUrl: row.profile_image_url || null,
    createdAt: row.created_at,
    updatedAt: row.updated_at,
  };
}

const PROFILE_COLUMNS =
  'id, name, email, profile_image_url, created_at, updated_at';

module.exports = {
  ALLOWED_IMAGE_TYPES,
  MAX_IMAGE_BYTES,
  PROFILE_COLUMNS,
  deleteStoredImage,
  detectImageType,
  mapProfile,
  normalizeEmail,
  normalizeName,
  validateProfileFields,
  validateProfileImage,
};
